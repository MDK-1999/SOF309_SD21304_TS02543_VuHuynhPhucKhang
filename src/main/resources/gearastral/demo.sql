-- H2 schema for an isolated SOF309 demo database.
CREATE TABLE Users (
    user_id       INT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    username      NVARCHAR(50) NOT NULL,
    password      NVARCHAR(255) NOT NULL,
    full_name     NVARCHAR(100) NOT NULL,
    email         NVARCHAR(100) NULL,
    phone         NVARCHAR(20) NULL,
    address       NVARCHAR(300) NULL,
    role          NVARCHAR(20) NOT NULL,
    is_active     SMALLINT DEFAULT 1 NOT NULL,
    created_at    TIMESTAMP(0) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    last_login    TIMESTAMP(0) NULL,

    CONSTRAINT PK_Users PRIMARY KEY (user_id),
    CONSTRAINT UQ_Users_Username UNIQUE (username),
    CONSTRAINT UQ_Users_Email UNIQUE NULLS DISTINCT (email),
    CONSTRAINT CK_Users_Role CHECK (role IN ('admin', 'staff', 'customer'))
);

CREATE TABLE Categories (
    cat_id         INT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    cat_name       NVARCHAR(100) NOT NULL,
    description    NVARCHAR(500) NULL,
    icon           NVARCHAR(30) DEFAULT 'PC' NOT NULL,
    is_active      SMALLINT DEFAULT 1 NOT NULL,

    CONSTRAINT PK_Categories PRIMARY KEY (cat_id),
    CONSTRAINT UQ_Categories_Name UNIQUE (cat_name)
);

CREATE TABLE Products (
    product_id     INT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    cat_id         INT NOT NULL,
    product_name   NVARCHAR(200) NOT NULL,
    brand          NVARCHAR(100) NULL,
    model          NVARCHAR(100) NULL,
    description    NVARCHAR(2000) NULL,
    price          DECIMAL(15,2) NOT NULL,
    stock_qty      INT DEFAULT 0 NOT NULL,
    specs          NVARCHAR(1000) NULL,
    image_url      NVARCHAR(500) NULL,
    is_active      SMALLINT DEFAULT 1 NOT NULL,
    created_at     TIMESTAMP(0) DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT PK_Products PRIMARY KEY (product_id),
    CONSTRAINT FK_Products_Categories FOREIGN KEY (cat_id)
        REFERENCES Categories(cat_id),
    CONSTRAINT CK_Products_Price CHECK (price >= 0),
    CONSTRAINT CK_Products_Stock CHECK (stock_qty >= 0)
);

CREATE TABLE Orders (
    order_id          INT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_id           INT NULL,
    staff_id          INT NULL,
    customer_name     NVARCHAR(100) NOT NULL,
    customer_phone    NVARCHAR(20) NULL,
    customer_email    NVARCHAR(100) NULL,
    shipping_addr     NVARCHAR(300) NULL,
    order_type        NVARCHAR(20) DEFAULT 'product' NOT NULL,
    total_amount      DECIMAL(15,2) DEFAULT 0 NOT NULL,
    discount          DECIMAL(15,2) DEFAULT 0 NOT NULL,
    final_amount      DECIMAL(15,2) DEFAULT 0 NOT NULL,
    status            NVARCHAR(20) DEFAULT 'pending' NOT NULL,
    payment_method    NVARCHAR(20) DEFAULT 'cod' NOT NULL,
    payment_status    NVARCHAR(20) DEFAULT 'unpaid' NOT NULL,
    notes             NVARCHAR(500) NULL,
    created_at        TIMESTAMP(0) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at        TIMESTAMP(0) DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT PK_Orders PRIMARY KEY (order_id),
    CONSTRAINT FK_Orders_Customer FOREIGN KEY (user_id)
        REFERENCES Users(user_id),
    CONSTRAINT FK_Orders_Staff FOREIGN KEY (staff_id)
        REFERENCES Users(user_id),
    CONSTRAINT CK_Orders_Type CHECK (order_type = 'product'),
    CONSTRAINT CK_Orders_Amounts CHECK (
        total_amount >= 0 AND discount >= 0 AND final_amount >= 0
        AND discount <= total_amount
        AND final_amount = total_amount - discount
    ),
    CONSTRAINT CK_Orders_Status CHECK (
        status IN ('pending', 'confirmed', 'processing', 'shipping', 'done', 'cancelled')
    ),
    CONSTRAINT CK_Orders_PaymentMethod CHECK (payment_method IN ('cod', 'qr')),
    CONSTRAINT CK_Orders_PaymentStatus CHECK (payment_status IN ('unpaid', 'paid', 'refunded'))
);

CREATE TABLE OrderItems (
    item_id        INT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    order_id       INT NOT NULL,
    product_id     INT NOT NULL,
    quantity       INT NOT NULL,
    unit_price     DECIMAL(15,2) NOT NULL,
    subtotal       DECIMAL(15,2) NOT NULL,

    CONSTRAINT PK_OrderItems PRIMARY KEY (item_id),
    CONSTRAINT FK_OrderItems_Orders FOREIGN KEY (order_id)
        REFERENCES Orders(order_id) ON DELETE CASCADE,
    CONSTRAINT FK_OrderItems_Products FOREIGN KEY (product_id)
        REFERENCES Products(product_id),
    CONSTRAINT CK_OrderItems_Quantity CHECK (quantity > 0),
    CONSTRAINT CK_OrderItems_UnitPrice CHECK (unit_price >= 0),
    CONSTRAINT CK_OrderItems_Subtotal CHECK (subtotal = quantity * unit_price)
);

CREATE TABLE StockImports (
    import_id       INT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    product_id      INT NOT NULL,
    staff_id        INT NULL,
    quantity        INT NOT NULL,
    unit_cost       DECIMAL(15,2) NULL,
    supplier        NVARCHAR(200) NULL,
    note            NVARCHAR(500) NULL,
    import_date     TIMESTAMP(0) DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT PK_StockImports PRIMARY KEY (import_id),
    CONSTRAINT FK_StockImports_Products FOREIGN KEY (product_id)
        REFERENCES Products(product_id),
    CONSTRAINT FK_StockImports_Staff FOREIGN KEY (staff_id)
        REFERENCES Users(user_id),
    CONSTRAINT CK_StockImports_Quantity CHECK (quantity > 0),
    CONSTRAINT CK_StockImports_UnitCost CHECK (unit_cost IS NULL OR unit_cost >= 0)
);

